-- Kích hoạt extension pgcrypto / uuid nếu cần
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- --------------------------------------------------------
-- 1. BẢNG HỒ SƠ CẦU THỦ (player_profiles)
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.player_profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT NOT NULL,
    avatar_url TEXT,
    position TEXT DEFAULT 'Tiền đạo',            -- Tiền đạo, Tiền vệ, Hậu vệ, Thủ môn
    preferred_foot TEXT DEFAULT 'Chân phải',      -- Chân phải, Chân trái, Hai chân
    jersey_number INT DEFAULT 10,
    club_team TEXT DEFAULT 'FC Baller',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- --------------------------------------------------------
-- 2. BẢNG BÀI TẬP KỶ LUẬT THÓI QUEN (football_habits)
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.football_habits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,                          -- Tâng bóng 500 cái, Chạy bứt tốc 3km...
    category TEXT NOT NULL,                       -- 'Kỹ thuật', 'Thể lực', 'Dinh dưỡng'
    target_value INT NOT NULL DEFAULT 1,          -- Giá trị mục tiêu
    unit TEXT NOT NULL DEFAULT 'lần',             -- 'lần', 'phút', 'km', 'lít'
    reminder_time TIME,
    color_value INT DEFAULT 4280209793,           -- Mã màu Hex integer
    icon_name TEXT DEFAULT 'sports_soccer',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- --------------------------------------------------------
-- 3. BẢNG LỊCH SỬ CHECK-IN KỶ LUẬT (habit_logs)
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.habit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habit_id BIGINT NOT NULL REFERENCES public.football_habits(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    date DATE NOT NULL DEFAULT CURRENT_DATE,      -- Định dạng yyyy-MM-dd
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    actual_value INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (habit_id, date)
);

-- --------------------------------------------------------
-- 4. BẢNG PHIÊN TẬP HUẤN LUYỆN BẤM GIỜ (training_drills_sessions)
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.training_drills_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    drill_name TEXT NOT NULL,                     -- Tên bài drill: Sút phạt hàng rào, Chạy dích dắc...
    duration_minutes INT NOT NULL,                -- Số phút tập thực tế
    sets_completed INT DEFAULT 1,                 -- Số hiệp hoàn thành
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- --------------------------------------------------------
-- 5. BẢNG NHẬT KÝ TRẬN ĐẤU & BUỔI TẬP (match_journals)
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.match_journals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    match_type TEXT NOT NULL DEFAULT 'Trận đấu',  -- 'Trận đấu' hoặc 'Buổi tập'
    rating INT CHECK (rating >= 1 AND rating <= 5), -- Đánh giá 1 - 5 sao
    goals INT DEFAULT 0,                          -- Số bàn thắng
    assists INT DEFAULT 0,                        -- Số kiến tạo
    review_content TEXT,                          -- Đánh giá phong độ, cảm nghĩ
    image_url TEXT,                               -- Link ảnh sân bóng từ Supabase Storage
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ========================================================
-- THIẾT LẬP BẢO MẬT ROW LEVEL SECURITY (RLS)
-- ========================================================
ALTER TABLE public.player_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.football_habits ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.habit_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.training_drills_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.match_journals ENABLE ROW LEVEL SECURITY;

-- 1. Policies cho player_profiles
CREATE POLICY "Profiles - Xem hồ sơ" ON public.player_profiles
    FOR SELECT TO authenticated USING (auth.uid() = id);

CREATE POLICY "Profiles - Thêm hồ sơ" ON public.player_profiles
    FOR INSERT TO authenticated WITH CHECK (auth.uid() = id);

CREATE POLICY "Profiles - Cập nhật hồ sơ" ON public.player_profiles
    FOR UPDATE TO authenticated USING (auth.uid() = id);

-- 2. Policies cho football_habits
CREATE POLICY "Habits - Toàn quyền chủ sở hữu" ON public.football_habits
    FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

-- 3. Policies cho habit_logs
CREATE POLICY "Logs - Toàn quyền chủ sở hữu" ON public.habit_logs
    FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

-- 4. Policies cho training_drills_sessions
CREATE POLICY "Drills - Toàn quyền chủ sở hữu" ON public.training_drills_sessions
    FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

-- 5. Policies cho match_journals
CREATE POLICY "Journals - Toàn quyền chủ sở hữu" ON public.match_journals
    FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

-- ========================================================
-- TRIGGER TỰ ĐỘNG TẠO BẢN GHI PROFILE KHI CÓ USER ĐĂNG KÝ MỚI
-- ========================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.player_profiles (id, full_name, avatar_url)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'full_name', 'Cầu thủ mới'),
    NEW.raw_user_meta_data->>'avatar_url'
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Gắn Trigger vào bảng auth.users
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ========================================================
-- 6. CẤU HÌNH STORAGE BUCKET CHO ẢNH ĐẠI DIỆN (avatars)
-- ========================================================
-- Tạo bucket 'avatars' công khai để lưu trữ avatar cầu thủ nếu dùng Supabase Storage
INSERT INTO storage.buckets (id, name, public)
VALUES ('avatars', 'avatars', true)
ON CONFLICT (id) DO NOTHING;

-- Policy 1: Mọi người đều có quyền xem ảnh đại diện công khai
CREATE POLICY "Public Read Avatars" ON storage.objects
    FOR SELECT USING (bucket_id = 'avatars');

-- Policy 2: Cầu thủ đã xác thực được phép tải ảnh lên thư mục của chính mình
CREATE POLICY "Auth Upload Avatars" ON storage.objects
    FOR INSERT TO authenticated WITH CHECK (bucket_id = 'avatars');

-- Policy 3: Cầu thủ đã xác thực được phép cập nhật ảnh của chính mình
CREATE POLICY "Auth Update Avatars" ON storage.objects
    FOR UPDATE TO authenticated USING (bucket_id = 'avatars');
