-- Chạy toàn bộ đoạn SQL này trong Supabase -> SQL Editor -> Run
-- Để tạo các bảng lưu trữ dữ liệu cho ứng dụng DCSleep (Nhóm 07 - 65KTPM)

CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  student_id TEXT NOT NULL DEFAULT '',
  class_name TEXT NOT NULL DEFAULT '65KTPM',
  password TEXT NOT NULL DEFAULT '123456',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.sleep_goals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bedtime_hour INT NOT NULL,
  bedtime_minute INT NOT NULL,
  wake_hour INT NOT NULL,
  wake_minute INT NOT NULL,
  target_duration_hours DOUBLE PRECISION NOT NULL,
  active_days TEXT NOT NULL,
  is_reminder_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.sleep_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sleep_time TIMESTAMPTZ NOT NULL,
  wake_time TIMESTAMPTZ NOT NULL,
  duration_hours DOUBLE PRECISION NOT NULL,
  wake_up_count INT NOT NULL DEFAULT 0,
  feeling_rating INT NOT NULL DEFAULT 3,
  note TEXT NOT NULL DEFAULT '',
  is_goal_met BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.nap_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  start_time TIMESTAMPTZ NOT NULL,
  duration_minutes INT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.ai_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text TEXT NOT NULL,
  is_user BOOLEAN NOT NULL,
  is_offline BOOLEAN NOT NULL DEFAULT FALSE,
  timestamp TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

